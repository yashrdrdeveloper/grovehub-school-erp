// Command gormtable creates GORM TableName methods for @GroveTable declarations.
package main

import (
 "bytes"
 "fmt"
 "go/ast"
 "go/format"
 "go/parser"
 "go/token"
 "os"
 "path/filepath"
 "regexp"
 "sort"
 "strings"
)

var validTable = regexp.MustCompile(`^[a-z_][a-z0-9_]*(\.[a-z_][a-z0-9_]*)?$`)

func main() {
 if len(os.Args)!=2 {fmt.Fprintln(os.Stderr,"usage: gormtable <entity-directory>");os.Exit(2)}
 if err:=generate(os.Args[1]);err!=nil {fmt.Fprintln(os.Stderr,err);os.Exit(1)}
}

func generate(dir string)error {
 entries,err:=os.ReadDir(dir);if err!=nil{return err}
 fset:=token.NewFileSet()
 var pkg string
 tables:=map[string]string{}
 existing:=map[string]bool{}
 for _,entry:=range entries {
  name:=entry.Name()
  if entry.IsDir()||!strings.HasSuffix(name,".go")||strings.HasSuffix(name,"_test.go")||name=="zz_grove_tables.gen.go" {continue}
  file,err:=parser.ParseFile(fset,filepath.Join(dir,name),nil,parser.ParseComments)
  if err!=nil{return err}
  if pkg=="" {pkg=file.Name.Name}else if pkg!=file.Name.Name {return fmt.Errorf("mixed packages in %s",dir)}
  for _,decl:=range file.Decls {
   switch d:=decl.(type) {
   case *ast.FuncDecl:
    if d.Name.Name!="TableName"||d.Recv==nil||len(d.Recv.List)!=1 {continue}
    recv:=d.Recv.List[0].Type
    if ptr,ok:=recv.(*ast.StarExpr);ok {recv=ptr.X}
    if id,ok:=recv.(*ast.Ident);ok {existing[id.Name]=true}
   case *ast.GenDecl:
    if d.Tok!=token.TYPE {continue}
    for _,spec:=range d.Specs {
     ts,ok:=spec.(*ast.TypeSpec);if !ok {continue}
     if _,ok:=ts.Type.(*ast.StructType);!ok {continue}
     doc:=ts.Doc;if doc==nil {doc=d.Doc}
     if doc==nil {continue}
     for _,comment:=range doc.List {
      text:=strings.TrimSpace(strings.TrimPrefix(comment.Text,"//"))
      if !strings.HasPrefix(text,"@GroveTable ") {continue}
      table:=strings.TrimSpace(strings.TrimPrefix(text,"@GroveTable "))
      if !validTable.MatchString(table) {return fmt.Errorf("%s: invalid @GroveTable %q",ts.Name.Name,table)}
      if old,ok:=tables[ts.Name.Name];ok&&old!=table {return fmt.Errorf("conflicting table declarations for %s",ts.Name.Name)}
      tables[ts.Name.Name]=table
     }
    }
   }
  }
 }
 if pkg=="" {return fmt.Errorf("no Go source files in %s",dir)}
 names:=make([]string,0,len(tables))
 for name:=range tables {
  if existing[name] {return fmt.Errorf("%s declares TableName manually and with @GroveTable",name)}
  names=append(names,name)
 }
 sort.Strings(names)
 var b strings.Builder
 b.WriteString("// Code generated by GroveHub gormtable. DO NOT EDIT.\npackage "+pkg+"\n\n")
 for _,name:=range names {fmt.Fprintf(&b,"func (%s) TableName() string { return %q }\n\n",name,tables[name])}
 output:=filepath.Join(dir,"zz_grove_tables.gen.go")
 if len(names)==0 {
  if err:=os.Remove(output);err!=nil&&!os.IsNotExist(err){return err}
  return nil
 }
 contents,err:=format.Source([]byte(b.String()));if err!=nil{return err}
 before,err:=os.ReadFile(output)
 if err==nil&&bytes.Equal(before,contents){return nil}
 if err!=nil&&!os.IsNotExist(err){return err}
 return os.WriteFile(output,contents,0644)
}
