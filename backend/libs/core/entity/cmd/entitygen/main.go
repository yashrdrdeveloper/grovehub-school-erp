// Command entitygen generates passive GORM entity boilerplate from a Go struct.
package main

import (
 "bytes"
 "flag"
 "fmt"
 "go/ast"
 "go/format"
 "go/parser"
 "go/printer"
 "go/token"
 "os"
 "path/filepath"
 "sort"
 "strconv"
 "strings"
 "unicode"
)

func main() {
 typ := flag.String("type", "", "name of the entity struct")
 table := flag.String("table", "", "schema-qualified GORM table name")
 dir := flag.String("dir", ".", "package directory")
 output := flag.String("output", "", "output file; defaults to zz_<type>_entity.gen.go")
 flag.Parse()
 if *typ == "" || *table == "" { fmt.Fprintln(os.Stderr, "-type and -table are required"); os.Exit(2) }
 if err := generate(*dir,*typ,*table,*output); err != nil { fmt.Fprintln(os.Stderr,err); os.Exit(1) }
}

func generate(dir, typeName, tableName, output string) error {
 if !validIdentifier(typeName) || strings.TrimSpace(tableName) != tableName || tableName == "" { return fmt.Errorf("invalid type or table name") }
 if output == "" { output = "zz_" + strings.ToLower(typeName) + "_entity.gen.go" }
 if filepath.Base(output) != output || !strings.HasSuffix(output,".go") {return fmt.Errorf("output must be a Go file name in the package directory")}
 fset := token.NewFileSet()
 packages, err := parser.ParseDir(fset,dir,func(info os.FileInfo)bool{return strings.HasSuffix(info.Name(),".go") && !strings.HasSuffix(info.Name(),"_test.go") && info.Name()!=output},parser.ParseComments)
 if err != nil {return err}
 if len(packages)!=1 {return fmt.Errorf("expected one Go package in %s, got %d",dir,len(packages))}
 var pkg *ast.Package
 for _, value := range packages { pkg=value }
 var target *ast.StructType
 existing := map[string]bool{}
 imports := map[string]string{}
 for _, file := range pkg.Files {
  for _, imp := range file.Imports {
   path,err:=strconv.Unquote(imp.Path.Value);if err!=nil{return err}
   alias:=filepath.Base(path);if imp.Name!=nil {alias=imp.Name.Name}
   if alias!="." && alias!="_" {imports[alias]=path}
  }
  for _, decl := range file.Decls {
   switch d:=decl.(type) {
   case *ast.FuncDecl:
    if d.Recv!=nil && len(d.Recv.List)>0 {
     switch recv:=d.Recv.List[0].Type.(type) {
     case *ast.Ident: if recv.Name==typeName {existing[d.Name.Name]=true}
     case *ast.StarExpr: if id,ok:=recv.X.(*ast.Ident);ok && id.Name==typeName {existing[d.Name.Name]=true}
     }
    } else if d.Name.Name=="New"+typeName {existing[d.Name.Name]=true}
   case *ast.GenDecl:
    for _, spec:=range d.Specs { if ts,ok:=spec.(*ast.TypeSpec);ok && ts.Name.Name==typeName {if st,ok:=ts.Type.(*ast.StructType);ok {target=st}else{return fmt.Errorf("%s is not a struct",typeName)}} }
   }
  }
 }
 if target==nil{return fmt.Errorf("struct %s not found",typeName)}
 type field struct{name,typ,param string}
 var fields []field
 usedImports:=map[string]string{}
 for _, node:=range target.Fields.List {
  if len(node.Names)==0 {return fmt.Errorf("embedded fields are not supported in %s",typeName)}
  var b bytes.Buffer
  if err:=printer.Fprint(&b,fset,node.Type);err!=nil{return err}
  ast.Inspect(node.Type,func(n ast.Node)bool{if s,ok:=n.(*ast.SelectorExpr);ok {if id,ok:=s.X.(*ast.Ident);ok {if path,found:=imports[id.Name];found {usedImports[id.Name]=path}}};return true})
  for _, name:=range node.Names {
   if !name.IsExported() {return fmt.Errorf("field %s must be exported for generated accessors",name.Name)}
   fields=append(fields,field{name:name.Name,typ:b.String(),param:lowerFirst(name.Name)})
  }
 }
 var b strings.Builder
 fmt.Fprintf(&b,"// Code generated by entitygen. DO NOT EDIT.\npackage %s\n\n",pkg.Name)
 if len(usedImports)>0 {
  keys:=make([]string,0,len(usedImports));for k:=range usedImports {keys=append(keys,k)};sort.Strings(keys)
  b.WriteString("import (\n")
  for _,k:=range keys {path:=usedImports[k];if k==filepath.Base(path) {fmt.Fprintf(&b,"%q\n",path)}else{fmt.Fprintf(&b,"%s %q\n",k,path)}}
  b.WriteString(")\n\n")
 }
 if !existing["TableName"] {fmt.Fprintf(&b,"func (%s) TableName() string { return %q }\n\n",typeName,tableName)}
 if !existing["New"+typeName] {
  args:=make([]string,0,len(fields));pairs:=make([]string,0,len(fields))
  for _,f:=range fields {args=append(args,f.param+" "+f.typ);pairs=append(pairs,f.name+": "+f.param)}
  fmt.Fprintf(&b,"func New%s(%s) %s { return %s{%s} }\n\n",typeName,strings.Join(args,", "),typeName,typeName,strings.Join(pairs,", "))
 }
 for _,f:=range fields {
  getter:="Get"+f.name
  if !existing[getter] {fmt.Fprintf(&b,"func (value %s) %s() %s { return value.%s }\n\n",typeName,getter,f.typ,f.name)}
  setter:="Set"+f.name
  if !existing[setter] {fmt.Fprintf(&b,"func (value %s) %s(%s %s) %s { value.%s = %s; return value }\n\n",typeName,setter,f.param,f.typ,typeName,f.name,f.param)}
 }
 formatted,err:=format.Source([]byte(b.String()));if err!=nil{return fmt.Errorf("generated Go is invalid: %w",err)}
 path:=filepath.Join(dir,output)
 current,err:=os.ReadFile(path)
 if err==nil && bytes.Equal(current,formatted) {return nil}
 if err!=nil && !os.IsNotExist(err) {return err}
 return os.WriteFile(path,formatted,0644)
}

func validIdentifier(s string)bool {if s=="" {return false};for i,r:=range s {if i==0 {if !unicode.IsLetter(r)&&r!='_' {return false}} else if !unicode.IsLetter(r)&&!unicode.IsDigit(r)&&r!='_' {return false}};return true}
func lowerFirst(s string)string {if s=="" {return s};r:=[]rune(s);r[0]=unicode.ToLower(r[0]);return string(r)}
