func TestPackageSelection(t *testing.T) {
    expect := NewWithT(t)
    backend := t.TempDir()
    for _, relative := range []string{"services/foundation", "services/identity", "libs/core", "launcher"} {
        expect.Expect(os.MkdirAll(filepath.Join(backend, relative), 0755)).To(Succeed())
    }
    selected, err := resolve(backend, "", "[\"foundation\",\"identity\"]")
    expect.Expect(err).NotTo(HaveOccurred())
    expect.Expect(names(selected)).To(Equal("foundation, identity"))

    selected, err = resolve(backend, "foundation", "")
    expect.Expect(err).NotTo(HaveOccurred())
    expect.Expect(names(selected)).To(Equal("foundation"))

    selected, err = resolve(backend, "", "[foundation,identity]")
    expect.Expect(err).NotTo(HaveOccurred())
    expect.Expect(names(selected)).To(Equal("foundation, identity"))

    selected, err = resolve(backend, "", "[\"\"]")
    expect.Expect(err).NotTo(HaveOccurred())
    expect.Expect(names(selected)).To(Equal("core, foundation, identity, launcher"))

    _, err = resolve(backend, "foundation", "[\"identity\"]")
    expect.Expect(err).To(HaveOccurred())
    _, err = resolve(backend, "foundation/../../other", "")
    expect.Expect(err).To(HaveOccurred())
    _, err = resolve(backend, "missing", "")
    expect.Expect(err).To(HaveOccurred())
}

func TestScoreMergesDuplicateInstrumentation(t *testing.T) {
    expect := NewWithT(t)
    profile := filepath.Join(t.TempDir(), "coverage.out")
    original := "mode: atomic\n" +
        "grovehub/example/file.go:1.1,2.5 2 0\n" +
        "grovehub/example/file.go:3.1,4.5 3 0\n" +
        "grovehub/example/file.go:1.1,2.5 2 7\n"
    expect.Expect(os.WriteFile(profile, []byte(original), 0644)).To(Succeed())
    total, covered, err := score(profile)
    expect.Expect(err).NotTo(HaveOccurred())
    expect.Expect(total).To(Equal(int64(5)))
    expect.Expect(covered).To(Equal(int64(2)))
    saved, err := os.ReadFile(profile)
    expect.Expect(err).NotTo(HaveOccurred())
    expect.Expect(strings.Count(string(saved), "file.go:1.1,2.5")).To(Equal(1))
    expect.Expect(string(saved)).To(ContainSubstring("file.go:1.1,2.5 2 7"))
}

func TestMaterializeAndCleanGeneratedSources(t *testing.T) {
    expect := NewWithT(t)
    backend := t.TempDir()
    owner := filepath.Join(backend, "services", "foundation")
    logical := filepath.Join(owner, "internal", "app", "person", "zz_test.gen.go")
    generated := filepath.Join(owner, ".generated", "internal", "app", "person", "zz_test.gen.go")
    overlay := filepath.Join(backend, ".generated", "overlay.json")
    manifest := filepath.Join(backend, ".generated", "unit-coverage", ".materialized-files")
    expect.Expect(os.MkdirAll(filepath.Dir(logical), 0755)).To(Succeed())
    expect.Expect(os.MkdirAll(filepath.Dir(generated), 0755)).To(Succeed())
    expect.Expect(os.MkdirAll(filepath.Dir(manifest), 0755)).To(Succeed())
    source := "// Code generated by a unit test. DO NOT EDIT.\npackage person\n"
    expect.Expect(os.WriteFile(generated, []byte(source), 0644)).To(Succeed())
    serialized, err := json.Marshal(overlayConfig{Replace:map[string]string{logical:generated}})
    expect.Expect(err).NotTo(HaveOccurred())
    expect.Expect(os.WriteFile(overlay, serialized, 0644)).To(Succeed())

    clean, err := materialize(overlay, manifest, []target{{name:"foundation",owner:owner}})
    expect.Expect(err).NotTo(HaveOccurred())
    bytes, err := os.ReadFile(logical)
    expect.Expect(err).NotTo(HaveOccurred())
    expect.Expect(string(bytes)).To(Equal(source))
    clean()
    _, err = os.Stat(logical)
    expect.Expect(os.IsNotExist(err)).To(BeTrue())

    // Interrupted processes can leave a durable manifest and an orphan.
    expect.Expect(os.WriteFile(logical, []byte(source), 0644)).To(Succeed())
    expect.Expect(os.WriteFile(manifest, []byte(logical+"\n"), 0600)).To(Succeed())
    expect.Expect(recoverGenerated(manifest, backend)).To(Succeed())
    _, err = os.Stat(logical)
    expect.Expect(os.IsNotExist(err)).To(BeTrue())

    // A modified file without a generated marker must never be deleted.
    expect.Expect(os.WriteFile(logical, []byte("package person\n"), 0644)).To(Succeed())
    expect.Expect(os.WriteFile(manifest, []byte(logical+"\n"), 0600)).To(Succeed())
    expect.Expect(recoverGenerated(manifest, backend)).To(HaveOccurred())
    _, err = os.Stat(logical)
    expect.Expect(err).NotTo(HaveOccurred())
}
