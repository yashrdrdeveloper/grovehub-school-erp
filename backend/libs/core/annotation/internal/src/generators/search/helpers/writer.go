package helpers

import (
	generatedoutput "grovehub/libs/core/annotation/internal/src/helpers/output"
	"fmt"
	"path/filepath"
	"sort"
	"strings"

	"grovehub/libs/core/annotation/internal/src/helpers/layout"
)

func Write(path,modulePath string,specs []spec)error{
	if len(specs)==0 {return fmt.Errorf("no search specifications to generate")}
	var b strings.Builder
	b.WriteString("// Code generated by GrooveHub @Searchable. DO NOT EDIT.\npackage impl\n\n")
	fmt.Fprintf(&b,"import (\n\"context\"\ncoresearch %q\ncoredatabase %q\n",layout.CoreImportPath+"/search",layout.CoreImportPath+"/database")
	// All @Searchable declarations in this service share its entity package.
	entityPath := modulePath + "/services/" + specs[0].service + "/entity"
    if strings.Contains(filepath.ToSlash(path), "/internal/app/repository/") {
        entityPath = modulePath + "/services/" + specs[0].service + "/internal/app/entity"
    }
    fmt.Fprintf(&b,"%q\n",entityPath)
	imports:=map[string]string{}
	for _,sp:=range specs {
		if sp.configImport=="" {continue}
		if old,ok:=imports[sp.configAlias];ok&&old!=sp.configImport {
			return fmt.Errorf("conflicting config package alias %s",sp.configAlias)
		}
		imports[sp.configAlias]=sp.configImport
	}
	aliases:=make([]string,0,len(imports))
	for name:=range imports {aliases=append(aliases,name)}
	sort.Strings(aliases)
	for _,name:=range aliases {fmt.Fprintf(&b,"%s %q\n",name,imports[name])}
	b.WriteString(")\n\n")
	for _,sp:=range specs{
		if sp.service!=specs[0].service{return fmt.Errorf("mixed service annotations")}
		fmt.Fprintf(&b,"func (repository *%s) searchGenerated(ctx context.Context, query coresearch.Query[string]) (coresearch.QueryResult[entity.%s], error) {\n",sp.impl,sp.entity)
		fmt.Fprintf(&b,"return coresearch.Execute[string, entity.%s](coredatabase.TransactionDB(ctx, repository.db).Model(&entity.%s{}).Table(entity.%s{}.TableName()+\" AS %s\").Select(\"%s.*\"), query, %s)\n}\n\n",sp.entity,sp.entity,sp.entity,sp.alias,sp.alias,sp.config)
	}
	return generatedoutput.WriteGo(path, []byte(b.String()), "format generated search code")
}
