package helpers

import (
	generatedoutput "github.com/yashrdrdeveloper/grovehub-school-erp/libs/backend/core/annotation/internal/src/helpers/output"
	"fmt"
	"path/filepath"
	"sort"
	"strings"

	"github.com/yashrdrdeveloper/grovehub-school-erp/libs/backend/core/annotation/internal/src/helpers/layout"
)

func WriteRoutes(modulePath, service string, groups []routeGroup, output string) error {
	var b strings.Builder
	b.WriteString("// Code generated by GrooveHub @Routes. DO NOT EDIT.\n")
	b.WriteString("// Route tiers are URL categories only; security enforcement is a separate gateway responsibility.\n")
	b.WriteString("package routes\n\nimport (\n\"net/http\"\n")
	fmt.Fprintf(&b, "httptracing %q\n", layout.CoreImportPath+"/http")
	imports := map[string]string{}
	for _, group := range groups {
		alias := groupImportAlias(group)
		importPath := modulePath + "/services/" + service + "/controller"
        if strings.Contains(filepath.ToSlash(output), "/internal/app/routes/") {
            importPath = modulePath + "/services/" + service + "/internal/app/controller"
        }
		if group.resource != "" { importPath += "/" + group.resource }
		if group.tier != "" { importPath += "/" + group.tier }
		imports[alias] = importPath
	}
	aliases := make([]string, 0, len(imports))
	for alias := range imports {
		aliases = append(aliases, alias)
	}
	sort.Strings(aliases)
	for _, alias := range aliases {
		fmt.Fprintf(&b, "%s %q\n", alias, imports[alias])
	}
	b.WriteString(")\n\n")
	for _, group := range groups {
		fmt.Fprintf(&b, "func %s(mux *http.ServeMux, c %s.%s) {\n",
			generatedRegistrationName(group), groupImportAlias(group), group.name)
		for _, item := range group.routes {
			pattern := item.verb + " " + item.path
			fmt.Fprintf(&b, "mux.Handle(%q, httptracing.ServiceHandler(%q, %q, http.HandlerFunc(c.%s)))\n",
				pattern, service, pattern, item.method)
		}
		b.WriteString("}\n\n")
	}
	// Annotations produce service-owned policies; the gateway has no knowledge
	// of service endpoint strings, and registration is deterministic.
	b.WriteString("func RouteLimits() map[string]int {\nreturn map[string]int{\n")
	for _, group := range groups {
		for _, item := range group.routes {
			if item.limit == 0 {
				continue
			}
			fmt.Fprintf(&b, "%q: %d,\n", item.verb+" "+item.path, item.limit)
		}
	}
	b.WriteString("}\n}\n\n")
	return generatedoutput.WriteGo(output, []byte(b.String()), "format generated routes")
}
