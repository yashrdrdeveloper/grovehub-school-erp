// Package gormtable creates GORM TableName methods for @Entity declarations.
package gormtable

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"grovehub/libs/core/annotation/internal/src/helpers/layout"
	generatedoutput "grovehub/libs/core/annotation/internal/src/helpers/output"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

var validTable = regexp.MustCompile(`^[a-z_][a-z0-9_]*(\.[a-z_][a-z0-9_]*)?$`)

func GenerateInto(dir, output string) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	fset := token.NewFileSet()
	var pkg string
	tables := map[string]string{}
	existing := map[string]bool{}
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") || strings.HasSuffix(name, ".gen.go") || strings.HasSuffix(name, "_gombok.go") {
			continue
		}
		file, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.ParseComments)
		if err != nil {
			return err
		}
		if pkg == "" {
			pkg = file.Name.Name
		} else if pkg != file.Name.Name {
			return fmt.Errorf("mixed packages in %s", dir)
		}
		for _, decl := range file.Decls {
			switch d := decl.(type) {
			case *ast.FuncDecl:
				if d.Name.Name != "TableName" || d.Recv == nil || len(d.Recv.List) != 1 {
					continue
				}
				recv := d.Recv.List[0].Type
				if ptr, ok := recv.(*ast.StarExpr); ok {
					recv = ptr.X
				}
				if id, ok := recv.(*ast.Ident); ok {
					existing[id.Name] = true
				}
			case *ast.GenDecl:
				if d.Tok != token.TYPE {
					continue
				}
				for _, ts := range layout.TypeSpecs(d) {
					if _, ok := ts.Type.(*ast.StructType); !ok {
						continue
					}
					doc := ts.Doc
					if doc == nil {
						doc = d.Doc
					}
					if doc == nil {
						continue
					}
					for _, comment := range doc.List {
						text := strings.TrimSpace(strings.TrimPrefix(comment.Text, "//"))
						if !strings.HasPrefix(text, "@Entity ") {
							continue
						}
						args := strings.Fields(strings.TrimSpace(strings.TrimPrefix(text, "@Entity ")))
						if len(args) < 1 || len(args) > 2 || (len(args) == 2 && args[1] != "mode=table") {
							return fmt.Errorf("%s: invalid @Entity options", ts.Name.Name)
						}
						table := args[0]
						if !validTable.MatchString(table) {
							return fmt.Errorf("%s: invalid @Entity %q", ts.Name.Name, table)
						}
						if old, ok := tables[ts.Name.Name]; ok && old != table {
							return fmt.Errorf("conflicting table declarations for %s", ts.Name.Name)
						}
						tables[ts.Name.Name] = table
					}
				}
			}
		}
	}
	if pkg == "" {
		return fmt.Errorf("no Go source files in %s", dir)
	}
	names := make([]string, 0, len(tables))
	for name := range tables {
		if existing[name] {
			return fmt.Errorf("%s declares TableName manually and with @Entity", name)
		}
		names = append(names, name)
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString("// Code generated by entity table mapping tool. DO NOT EDIT.\npackage " + pkg + "\n\n")
	for _, name := range names {
		fmt.Fprintf(&b, "func (%s) TableName() string { return %q }\n\n", name, tables[name])
	}
	if err := os.MkdirAll(filepath.Dir(output), 0755); err != nil {
		return err
	}
	if len(names) == 0 {
		if err := os.Remove(output); err != nil && !os.IsNotExist(err) {
			return err
		}
		return nil
	}
	return generatedoutput.WriteGo(output, []byte(b.String()), "")
}
