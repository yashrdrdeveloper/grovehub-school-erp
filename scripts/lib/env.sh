#!/usr/bin/env bash
set -Eeuo pipefail

load_backend_runtime_env() {
  local env_file="${REPO_ROOT}/.env"
  [[ -f "${env_file}" ]] || return 0

  set +u
  # shellcheck disable=SC1090
  source "${env_file}"
  set -u

  local name
  for name in \
    DATABASE_URL \
    GROVEHUB_LOG_LEVELS \
    GROVEHUB_TRACE_SAMPLE_RATIO \
    GROVEHUB_METRIC_EXPORT_INTERVAL \
    GROVEHUB_GMAIL_CLIENT_ID \
    GROVEHUB_GMAIL_CLIENT_SECRET \
    GROVEHUB_GMAIL_REDIRECT_URI \
    GROVEHUB_GMAIL_PUBSUB_TOPIC \
    GROVEHUB_GMAIL_PUBSUB_AUDIENCE \
    GROVEHUB_GMAIL_PUBSUB_SERVICE_ACCOUNT \
    GROVEHUB_OUTLOOK_CLIENT_ID \
    GROVEHUB_OUTLOOK_CLIENT_SECRET \
    GROVEHUB_OUTLOOK_REDIRECT_URI \
    GROVEHUB_OUTLOOK_TENANT \
    GROVEHUB_INTEGRATION_ENCRYPTION_KEY \
    MAIL_INFRASTRUCTURE_SMTP_HOST \
    MAIL_INFRASTRUCTURE_SMTP_PORT \
    MAIL_INFRASTRUCTURE_DKIM_STATE_DIR \
    OTEL_SERVICE_VERSION \
    OTEL_SERVICE_INSTANCE_ID \
    OTEL_DEPLOYMENT_ENVIRONMENT; do
    if [[ -n "${!name+x}" ]]; then
      export "${name}"
    fi
  done
}
