#!/usr/bin/env bash
set -Eeuo pipefail

load_backend_runtime_env() {
  local env_file="${REPO_ROOT}/.env"
  if [[ -f "${env_file}" ]]; then
    set +u
    # shellcheck disable=SC1090
    source "${env_file}"
    set -u
  fi

  local name
  for name in \
    DATABASE_URL \
    GROVEHUB_MESSAGING_PROVIDER \
    GROVEHUB_NATS_URL \
    GROVEHUB_NATS_QUEUE_GROUP_PREFIX \
    GROVEHUB_NATS_DURABLE_PREFIX \
    GROVEHUB_LOG_LEVELS \
    GROVEHUB_TRACE_SAMPLE_RATIO \
    GROVEHUB_METRIC_EXPORT_INTERVAL \
    GROVEHUB_GMAIL_CLIENT_ID \
    GROVEHUB_GMAIL_CLIENT_SECRET \
    GROVEHUB_GMAIL_REDIRECT_URI \
    GROVEHUB_GMAIL_PUBSUB_TOPIC \
    GROVEHUB_GMAIL_PUBSUB_AUDIENCE \
    GROVEHUB_GMAIL_PUBSUB_SERVICE_ACCOUNT \
    GROVEHUB_OUTLOOK_CLIENT_ID \
    GROVEHUB_OUTLOOK_CLIENT_SECRET \
    GROVEHUB_OUTLOOK_REDIRECT_URI \
    GROVEHUB_OUTLOOK_TENANT \
    GROVEHUB_INTEGRATION_ENCRYPTION_KEY \
    IDENTITY_ALLOWED_ORIGIN \
    IDENTITY_ADMIN_ACCOUNT_IDS \
    IDENTITY_RBAC_MODE \
    IDENTITY_SETUP_URL \
    IDENTITY_RESET_URL \
    IDENTITY_INVITATION_KEY_B64 \
    IDENTITY_SYSTEM_MAIL_TENANT_ID \
    IDENTITY_SYSTEM_MAIL_CONNECTION_ID \
    MAIL_INFRASTRUCTURE_SMTP_HOST \
    MAIL_INFRASTRUCTURE_SMTP_PORT \
    MAIL_INFRASTRUCTURE_DKIM_STATE_DIR \
    OTEL_SERVICE_VERSION \
    OTEL_SERVICE_INSTANCE_ID \
    OTEL_DEPLOYMENT_ENVIRONMENT; do
    if [[ -n "${!name+x}" ]]; then
      export "${name}"
    fi
  done

  # Developer defaults belong to launcher scripts, not Go configuration.
  export GROVEHUB_MESSAGING_PROVIDER="${GROVEHUB_MESSAGING_PROVIDER:-nats}"
  export GROVEHUB_NATS_URL="${GROVEHUB_NATS_URL:-nats://127.0.0.1:${NATS_CLIENT_PORT:-4222}}"
  export GROVEHUB_NATS_QUEUE_GROUP_PREFIX="${GROVEHUB_NATS_QUEUE_GROUP_PREFIX:-grovehub}"
  export GROVEHUB_NATS_DURABLE_PREFIX="${GROVEHUB_NATS_DURABLE_PREFIX:-grovehub}"
}
