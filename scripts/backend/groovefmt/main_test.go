func TestFormattingAndIdempotence(t *testing.T) {
	path := filepath.Join(t.TempDir(), "client.go")
	input := `package client
import "context"
type Client interface {
 CreatePerson(ctx context.Context,
 request string,
 ) (string, bool, error)
 UpdatePerson(
 ctx context.Context,
 personRequest string,
 request string,
 ) (string, error)
}
func Foo(
 a string,
 b int,
) (string, error) {return a,nil}
const X=1
type Person struct {Name string}
`
	if err := os.WriteFile(path, []byte(input), 0600); err != nil {
		t.Fatal(err)
	}
	if err := formatFile(path); err != nil {
		t.Fatal(err)
	}
	first, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	for _, expected := range []string{
		"CreatePerson(ctx context.Context, request string) (string, bool, error)",
		"UpdatePerson(ctx context.Context, personRequest string, request string) (string, error)",
		"func Foo(a string, b int) (string, error)",
		"}\n\nfunc Foo",
		"}\n\nconst X = 1\n\ntype Person",
	} {
		if !strings.Contains(string(first), expected) {
			t.Errorf("missing %q in:\n%s", expected, first)
		}
	}
	if err := formatFile(path); err != nil {
		t.Fatal(err)
	}
	second, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(first, second) {
		t.Fatalf("formatter is not idempotent:\nfirst:\n%s\nsecond:\n%s", first, second)
	}
}

func TestCommentedSignaturePreserved(t *testing.T) {
	path := filepath.Join(t.TempDir(), "client.go")
	input := `package client
type Client interface {
 Do(
 // preserve this meaningful comment
 value string,
 ) error
}
`
	if err := os.WriteFile(path, []byte(input), 0600); err != nil {
		t.Fatal(err)
	}
	if err := formatFile(path); err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(data), "// preserve this meaningful comment") {
		t.Fatalf("signature comment lost:\n%s", data)
	}
}

func TestGeneratedFileUnchanged(t *testing.T) {
	path := filepath.Join(t.TempDir(), "generated.go")
	input := []byte("// Code generated by example. DO NOT EDIT.\npackage client\nconst X=1\n")
	if err := os.WriteFile(path, input, 0600); err != nil {
		t.Fatal(err)
	}
	if err := formatFile(path); err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(input, data) {
		t.Fatal("generated file was modified")
	}
}

func TestCheckFileEnforcesSingleLineSignaturesWithoutWriting(t *testing.T) {
	path := filepath.Join(t.TempDir(), "repository.go")
	input := []byte("package repository\nfunc Find(\n ctx string,\n id string,\n) error { return nil }\n")
	if err := os.WriteFile(path, input, 0600); err != nil {
		t.Fatal(err)
	}
	if err := checkFile(path); err == nil {
		t.Fatal("expected formatting lint to reject multiline signature")
	}
	unchanged, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(unchanged, input) {
		t.Fatal("formatting lint must not modify source")
	}
	if err := formatFile(path); err != nil {
		t.Fatal(err)
	}
	if err := checkFile(path); err != nil {
		t.Fatalf("expected formatted source to pass lint: %v", err)
	}
}
